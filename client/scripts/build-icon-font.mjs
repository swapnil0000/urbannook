#!/usr/bin/env node
/**
 * Font Awesome, only the icons the site uses — generated at build time, never committed.
 *
 * The site used to load Font Awesome 6.4 from jsdelivr: 4 stylesheets (~23 KB) plus the
 * solid + brands + regular fonts (~270 KB) with every one of its ~2,000 icons, from a
 * third host, at top priority, on every page — on mobile that fought the hero image and
 * the app's own CSS for bandwidth (PageSpeed: render-blocking / network payload / LCP).
 *
 * generateIconFont() scans src/ and index.html for `fa-<name>` and writes, from the
 * @fortawesome/fontawesome-free package in node_modules:
 *   src/generated/fa/fa-{solid-900,regular-400,brands-400}.woff2   (subsets, ~15 KB total)
 *   src/generated/fa-subset.css                                    (base classes + used icons)
 * src/generated/ is git-ignored (no font binaries in the repo). The Vite plugin in
 * vite.config.js runs this at the start of every build and dev server, so every way of
 * building (npm scripts, Jenkins' `npx vite build`, SSR build) gets a fresh, complete set.
 * Vite fingerprints the fonts like any other asset (cached for a year). main.jsx imports
 * the CSS.
 *
 * By hand:  npm run icons
 * Icon names built at runtime (`fa-${x}`) are found only when the full name appears
 * somewhere in the source as a string, e.g. icon="fa-user" — keep it that way. Prefixes
 * listed in PARTIAL are expanded.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import subsetFont from 'subset-font';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FA = path.join(ROOT, 'node_modules/@fortawesome/fontawesome-free');
const OUT_DIR = path.join(ROOT, 'src/generated');
const OUT_FONTS = path.join(OUT_DIR, 'fa');
const OUT_CSS = path.join(OUT_DIR, 'fa-subset.css');

// `fa-chevron-${dir}` and similar: every icon starting with these.
const PARTIAL = ['fa-chevron-'];
// Class names that are not icons.
const NOT_ICONS = new Set(['fa-solid', 'fa-regular', 'fa-brands', 'fa-spin', 'fa-solid-900', 'fa-regular-400', 'fa-brands-400', 'fa-subset']);

const FONTS = [
  ['solid-900', 'Font Awesome 6 Free', 900],
  ['regular-400', 'Font Awesome 6 Free', 400],
  ['brands-400', 'Font Awesome 6 Brands', 400],
];

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (p !== OUT_DIR) walk(p, out); } else if (/\.(jsx?|tsx?|html|css)$/.test(e.name)) out.push(p);
  }
  return out;
}

/** Build the subset fonts + CSS. Returns { icons, unknown, bytes }. Skips the work when nothing changed. */
export async function generateIconFont({ log = console.log } = {}) {
  // name → codepoint, from Font Awesome's own CSS (aliases included; brands.css has the brand icons).
  const codepoints = new Map();
  for (const file of ['css/fontawesome.css', 'css/brands.css']) {
    const css = fs.readFileSync(path.join(FA, file), 'utf8');
    for (const m of css.matchAll(/\.(fa-[a-z0-9-]+):{1,2}before\s*\{\s*content:\s*"\\([0-9a-f]+)"/g)) codepoints.set(m[1], parseInt(m[2], 16));
  }

  const used = new Set();
  for (const f of [...walk(path.join(ROOT, 'src')), path.join(ROOT, 'index.html')]) {
    for (const m of fs.readFileSync(f, 'utf8').matchAll(/fa-[a-z0-9-]+/g)) used.add(m[0]);
  }
  for (const pre of PARTIAL) for (const n of codepoints.keys()) if (n.startsWith(pre)) used.add(n);

  const icons = [...used].filter((n) => codepoints.has(n)).sort();
  const unknown = [...used].filter((n) => !codepoints.has(n) && !NOT_ICONS.has(n) && !PARTIAL.includes(n)).sort();

  const rules = icons.map((n) => `.${n}::before{content:"\\${codepoints.get(n).toString(16)}"}`).join('\n');
  const css = `/* Generated by scripts/build-icon-font.mjs at build time — not committed, do not edit. */
${FONTS.map(([file, family, weight]) => `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:block;src:url("./fa/fa-${file}.woff2") format("woff2")}`).join('\n')}
.fa,.fas,.far,.fab,.fa-solid,.fa-regular,.fa-brands{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}
.fa,.fas,.fa-solid{font-family:"Font Awesome 6 Free";font-weight:900}
.far,.fa-regular{font-family:"Font Awesome 6 Free";font-weight:400}
.fab,.fa-brands{font-family:"Font Awesome 6 Brands";font-weight:400}
.fa-spin{animation:fa-spin 2s linear infinite}
@keyframes fa-spin{0%{transform:rotate(0deg)}to{transform:rotate(360deg)}}
@media (prefers-reduced-motion:reduce){.fa-spin{animation:none}}
${rules}
`;

  // Same icons as last time and all fonts present → nothing to do (fast dev restarts).
  const upToDate = fs.existsSync(OUT_CSS) && fs.readFileSync(OUT_CSS, 'utf8') === css
    && FONTS.every(([file]) => fs.existsSync(path.join(OUT_FONTS, `fa-${file}.woff2`)));
  if (upToDate) return { icons, unknown, bytes: null };

  const text = String.fromCodePoint(...new Set(icons.map((n) => codepoints.get(n))));
  fs.mkdirSync(OUT_FONTS, { recursive: true });
  let bytes = 0;
  for (const [file] of FONTS) {
    const sub = await subsetFont(fs.readFileSync(path.join(FA, `webfonts/fa-${file}.ttf`)), text, { targetFormat: 'woff2' });
    fs.writeFileSync(path.join(OUT_FONTS, `fa-${file}.woff2`), sub);
    bytes += sub.length;
  }
  fs.writeFileSync(OUT_CSS, css);
  log(`[icons] ${icons.length} Font Awesome icons, fonts ${(bytes / 1024).toFixed(1)} KB → src/generated/`);
  if (unknown.length) log(`[icons] not Font Awesome 6.4 icon names (ignored): ${unknown.join(', ')}`);
  return { icons, unknown, bytes };
}

// CLI: npm run icons
if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  await generateIconFont();
}
